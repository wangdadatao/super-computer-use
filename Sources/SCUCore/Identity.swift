import SCUWire

/// 候选键档位。数值越小越稳定、越抗变化。
public enum KeyLevel: Int, Comparable, Sendable, CaseIterable {
    case k1 = 1  // 显式标识符
    case k2      // role + subrole + title + 祖先 role 路径
    case k3      // role + subrole + 祖先 role 路径
    case k4      // 逐级「同 role 兄弟序号」的完整位置路径

    public static func < (a: KeyLevel, b: KeyLevel) -> Bool { a.rawValue < b.rawValue }
    public var label: String { "K\(rawValue)" }
}

/// 哪些 `AXIdentifier` 算作"显式标识符"。
///
/// 形如 `_NS:61` 的值看起来是 AppKit 自动生成的，稳定性未知。
/// ADR-0013 的 K4 门槛口径规定判定时**不计入**（保守），
/// 另以 `inclusive` 统计"若计入"的比例，用于判断该规则是否过严。
public struct IdentifierPolicy: Sendable, Equatable {
    public var excludeAutoGenerated: Bool

    public static let conservative = IdentifierPolicy(excludeAutoGenerated: true)
    public static let inclusive = IdentifierPolicy(excludeAutoGenerated: false)

    func accepts(_ id: String) -> Bool {
        guard excludeAutoGenerated else { return true }
        return !Self.isAutoGenerated(id)
    }

    /// `_NS:` 后全是数字。
    static func isAutoGenerated(_ id: String) -> Bool {
        guard id.hasPrefix("_NS:") else { return false }
        let rest = id.dropFirst(4)
        return !rest.isEmpty && rest.allSatisfy(\.isNumber)
    }
}

/// K2 里用什么作"标签"。
///
/// **实验性**：基线显示访达的大量控件没有 `title`，标签很可能在 `AXDescription` 里。
/// 两种口径并存是为了用数据回答"是否把 description 纳入 K2"，结论出来后收敛为一种。
public enum LabelPolicy: Sendable, Equatable {
    case titleOnly
    case titleOrDescription

    func label(_ n: AXNode) -> String? {
        switch self {
        case .titleOnly: return n.title
        case .titleOrDescription: return n.title ?? n.description
        }
    }
}

/// 一个元素的身份计算结果。
public struct ElementIdentity: Sendable, Equatable {
    /// 从根出发的子节点下标序列。根为空。
    public var path: [Int]
    public var role: String
    public var title: String?
    public var identifier: String?
    /// 各档候选键。K2 在元素没有 title 时不存在（它与 K3 等价，保留只会让档位标注失真）。
    public var candidates: [KeyLevel: String]
    public var matchLevel: KeyLevel
    /// 匹配键 = 第一个在整棵树中唯一的候选键，带档位前缀。
    public var matchKey: String
    /// 位于菜单栏子树内（祖先含 `AXMenuBar`）。
    public var inMenuBar: Bool
    /// 窗口内可交互元素：role 属于可交互集合，且**不在菜单栏内**（ADR-0013 口径 v2）。
    public var isInteractive: Bool
}

/// 为整棵树的每个元素计算候选键并定出匹配键。纯函数，无状态；句柄注册表在它之上另建。
// @project-doc docs/architecture/element_identity.md#candidate_keys
public enum IdentityAnalyzer {
    /// 判定"可交互元素"的 role 集合。ADR-0013 的初始定义；`AXNode` 尚无 action 列表，先按 role 近似。
    /// 菜单栏子树内的元素另计（口径 v2，见 ADR-0013 追加记录）。
    public static let interactiveRoles: Set<String> = [
        "AXButton", "AXCheckBox", "AXRadioButton", "AXTextField", "AXTextArea", "AXComboBox",
        "AXPopUpButton", "AXMenuButton", "AXMenuItem", "AXLink", "AXSlider", "AXSearchField",
    ]

    /// 窗口内可交互元素少于此数时，该应用的 K4 比例不具统计意义，不参与门槛判定。
    public static let minInteractiveSample = 20

    private struct Raw {
        var node: AXNode
        var path: [Int]
        var rolePath: [String]      // 含自身
        var ordinalPath: [String]   // 每级 "Role[同 role 兄弟序号]"，含自身
    }

    /// 先序遍历，返回每个元素的身份。顺序与先序一致。
    public static func analyze(
        _ root: AXNode, policy: IdentifierPolicy = .conservative, labels: LabelPolicy = .titleOnly
    ) -> [ElementIdentity] {
        var raws: [Raw] = []
        collect(root, path: [], rolePath: [], ordinalPath: [], ordinal: 0, into: &raws)

        // 候选键（K4 单独处理：由位置唯一决定，天然树内唯一）。
        struct Cands { var k1: String?; var k2: String?; var k3: String; var k4: String }
        let sep = "\u{1F}"
        let cands: [Cands] = raws.map { r in
            let n = r.node
            let pathText = r.rolePath.joined(separator: "/")
            let k1 = n.identifier.flatMap { policy.accepts($0) ? "K1:" + $0 : nil }
            let k2 = labels.label(n).map { "K2:" + [n.role, n.subrole ?? "", $0, pathText].joined(separator: sep) }
            let k3 = "K3:" + [n.role, n.subrole ?? "", pathText].joined(separator: sep)
            let k4 = "K4:" + r.ordinalPath.joined(separator: "/")
            return Cands(k1: k1, k2: k2, k3: k3, k4: k4)
        }

        // 统计 K1~K3 在整棵树中的出现次数，用于判断"是否唯一"。
        var count: [String: Int] = [:]
        for c in cands {
            if let k = c.k1 { count[k, default: 0] += 1 }
            if let k = c.k2 { count[k, default: 0] += 1 }
            count[c.k3, default: 0] += 1
        }

        return zip(raws, cands).map { r, c in
            var dict: [KeyLevel: String] = [:]
            if let k = c.k1 { dict[.k1] = k }
            if let k = c.k2 { dict[.k2] = k }
            dict[.k3] = c.k3
            dict[.k4] = c.k4

            let (level, key): (KeyLevel, String)
            if let k = c.k1, count[k] == 1 { (level, key) = (.k1, k) }
            else if let k = c.k2, count[k] == 1 { (level, key) = (.k2, k) }
            else if count[c.k3] == 1 { (level, key) = (.k3, c.k3) }
            else { (level, key) = (.k4, c.k4) }

            return ElementIdentity(
                path: r.path, role: r.node.role, title: r.node.title, identifier: r.node.identifier,
                candidates: dict, matchLevel: level, matchKey: key,
                inMenuBar: r.rolePath.contains("AXMenuBar"),
                isInteractive: interactiveRoles.contains(r.node.role) && !r.rolePath.contains("AXMenuBar"))
        }
    }

    private static func collect(
        _ node: AXNode, path: [Int], rolePath: [String], ordinalPath: [String], ordinal: Int,
        into out: inout [Raw]
    ) {
        let rp = rolePath + [node.role]
        let op = ordinalPath + ["\(node.role)[\(ordinal)]"]
        out.append(Raw(node: node, path: path, rolePath: rp, ordinalPath: op))
        var seen: [String: Int] = [:]
        for (i, child) in node.children.enumerated() {
            let n = seen[child.role, default: 0]
            seen[child.role] = n + 1
            collect(child, path: path + [i], rolePath: rp, ordinalPath: op, ordinal: n, into: &out)
        }
    }

    public static func report(
        _ root: AXNode, policy: IdentifierPolicy = .conservative, labels: LabelPolicy = .titleOnly
    ) -> IdentityReport {
        let ids = analyze(root, policy: policy, labels: labels)
        var all = LevelDistribution()
        var interactive = LevelDistribution()
        var menu = LevelDistribution()
        var byRole: [String: LevelDistribution] = [:]
        for e in ids {
            all.add(e.matchLevel)
            if e.inMenuBar { menu.add(e.matchLevel) }
            if e.isInteractive {
                interactive.add(e.matchLevel)
                byRole[e.role, default: LevelDistribution()].add(e.matchLevel)
            }
        }
        return IdentityReport(all: all, interactive: interactive, menuBar: menu, interactiveByRole: byRole)
    }
}

public struct LevelDistribution: Sendable, Equatable {
    public private(set) var counts: [KeyLevel: Int] = [:]
    public private(set) var total = 0

    public init() {}

    mutating func add(_ l: KeyLevel) {
        counts[l, default: 0] += 1
        total += 1
    }

    public func count(_ l: KeyLevel) -> Int { counts[l] ?? 0 }

    /// 某档占比；总数为 0 时为 nil（不是 0——没有样本不等于没有问题）。
    public func ratio(_ l: KeyLevel) -> Double? {
        total == 0 ? nil : Double(count(l)) / Double(total)
    }
}

public struct IdentityReport: Sendable, Equatable {
    /// 整棵树口径（照常记录，不参与门槛判定）。
    public var all: LevelDistribution
    /// 窗口内可交互元素口径（ADR-0013 的 K4 门槛口径，不含菜单栏）。
    public var interactive: LevelDistribution
    /// 菜单栏子树内的全部元素。单独呈现，不参与门槛判定。
    public var menuBar: LevelDistribution
    /// 可交互元素按 role 拆分。用于发现某个 role 把整体比例拉偏（口径检查）。
    public var interactiveByRole: [String: LevelDistribution]

    public func byRoleText() -> String {
        interactiveByRole.sorted { $0.value.total > $1.value.total }.map { role, d in
            let k4 = d.ratio(.k4).map { String(format: "%5.1f%%", $0 * 100) } ?? "    -"
            return "  \(role.padding(toLength: 16, withPad: " ", startingAt: 0)) 共 \(String(format: "%4d", d.total))  K4 \(String(format: "%4d", d.count(.k4))) \(k4)"
        }.joined(separator: "\n")
    }

    /// 文本表。基线阶段只呈现分布，**不给出成败结论**。
    public func text(title: String) -> String {
        func row(_ name: String, _ d: LevelDistribution) -> String {
            let cells = KeyLevel.allCases.map { l -> String in
                let p = d.ratio(l).map { String(format: "%5.1f%%", $0 * 100) } ?? "    -"
                return "\(l.label) \(String(format: "%5d", d.count(l))) \(p)"
            }
            return "  \(name)（\(d.total)）  " + cells.joined(separator: "   ")
        }
        var lines = [title, row("整棵树      ", all), row("窗口内可交互", interactive), row("菜单栏      ", menuBar)]
        if interactive.total < IdentityAnalyzer.minInteractiveSample {
            lines.append("  ⚠️ 窗口内可交互元素 \(interactive.total) 个，少于 \(IdentityAnalyzer.minInteractiveSample)：样本不足，不得据此判定")
        }
        return lines.joined(separator: "\n")
    }
}
