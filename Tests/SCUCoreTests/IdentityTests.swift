import Testing

@testable import SCUCore
@testable import SCUWire

@Suite struct IdentityTests {
    static func win(_ children: [AXNode]) -> AXNode { AXNode(role: "AXWindow", children: children) }

    static func level(of path: [Int], in root: AXNode, policy: IdentifierPolicy = .conservative) -> KeyLevel {
        IdentityAnalyzer.analyze(root, policy: policy).first { $0.path == path }!.matchLevel
    }

    @Test func uniqueIdentifierIsK1() {
        let root = Self.win([AXNode(role: "AXButton", title: "OK", identifier: "okButton")])
        #expect(Self.level(of: [0], in: root) == .k1)
    }

    @Test func autoGeneratedIdentifierIsExcludedUnderConservativePolicy() {
        let root = Self.win([AXNode(role: "AXButton", title: "OK", identifier: "_NS:61")])
        #expect(Self.level(of: [0], in: root, policy: .conservative) == .k2)
        #expect(Self.level(of: [0], in: root, policy: .inclusive) == .k1)
    }

    @Test func nonDigitNSIdentifierIsNotTreatedAsAutoGenerated() {
        #expect(!IdentifierPolicy.isAutoGenerated("_NS:abc"))
        #expect(!IdentifierPolicy.isAutoGenerated("_NS:"))
        #expect(IdentifierPolicy.isAutoGenerated("_NS:8"))
    }

    @Test func duplicateIdentifierDoesNotCountAsUnique() {
        let root = Self.win([
            AXNode(role: "AXButton", title: "A", identifier: "dup"),
            AXNode(role: "AXButton", title: "B", identifier: "dup"),
        ])
        // K1 重复 → 退到 K2，各自 title 不同而唯一
        #expect(Self.level(of: [0], in: root) == .k2)
        #expect(Self.level(of: [1], in: root) == .k2)
    }

    @Test func distinctTitlesGiveK2() {
        let root = Self.win([AXNode(role: "AXButton", title: "A"), AXNode(role: "AXButton", title: "B")])
        #expect(Self.level(of: [0], in: root) == .k2)
    }

    @Test func missingTitleSkipsK2AndReportsK3() {
        let root = Self.win([AXNode(role: "AXTextField")])
        let e = IdentityAnalyzer.analyze(root).first { $0.path == [0] }!
        #expect(e.matchLevel == .k3)
        #expect(e.candidates[.k2] == nil)
    }

    @Test func sameRoleSameTitleSiblingsFallToK4() {
        let root = Self.win([AXNode(role: "AXButton", title: "X"), AXNode(role: "AXButton", title: "X")])
        #expect(Self.level(of: [0], in: root) == .k4)
        #expect(Self.level(of: [1], in: root) == .k4)
    }

    /// 回归：文档曾声称 "K4 = K3 + 同级序号，必然唯一"。但 K3 的路径只含 role、不含祖先序号，
    /// 两个相同的 Row 里各有一个相同的 TextField 时，"同级序号"两边都是 0，K4 仍然相撞。
    /// K4 必须带上每一级祖先的序号才能保证唯一。
    @Test func cousinsWithIdenticalSubtreesGetDistinctMatchKeys() {
        let row = AXNode(role: "AXRow", children: [AXNode(role: "AXTextField")])
        let root = Self.win([AXNode(role: "AXList", children: [row, row, row])])
        let tfs = IdentityAnalyzer.analyze(root).filter { $0.role == "AXTextField" }
        #expect(tfs.count == 3)
        #expect(tfs.allSatisfy { $0.matchLevel == .k4 })
        #expect(Set(tfs.map(\.matchKey)).count == 3)
    }

    @Test func ordinalCountsOnlySameRoleSiblings() {
        // 插入一个不同 role 的兄弟，不应改变既有 Button 的 K4。
        let a = Self.win([AXNode(role: "AXButton", title: "X"), AXNode(role: "AXButton", title: "X")])
        let b = Self.win([AXNode(role: "AXStaticText"), AXNode(role: "AXButton", title: "X"), AXNode(role: "AXButton", title: "X")])
        let ka = IdentityAnalyzer.analyze(a).first { $0.path == [1] }!.matchKey
        let kb = IdentityAnalyzer.analyze(b).first { $0.path == [2] }!.matchKey
        #expect(ka == kb)
    }

    @Test func matchKeysAreUniqueAcrossArbitraryTrees() {
        // 确定性伪随机树：重复的 role/title 很多，逼出碰撞。
        var seed: UInt64 = 0x9E37_79B9_7F4A_7C15
        func next(_ n: Int) -> Int {
            seed = seed &* 6364136223846793005 &+ 1442695040888963407
            return Int((seed >> 33) % UInt64(n))
        }
        func tree(depth: Int) -> AXNode {
            let roles = ["AXGroup", "AXButton", "AXRow", "AXTextField"]
            let titles: [String?] = [nil, "a", "b"]
            let kids = depth == 0 ? [] : (0..<next(5)).map { _ in tree(depth: depth - 1) }
            return AXNode(
                role: roles[next(roles.count)], title: titles[next(titles.count)],
                identifier: next(4) == 0 ? "id\(next(3))" : nil, children: kids)
        }
        for _ in 0..<50 {
            let ids = IdentityAnalyzer.analyze(tree(depth: 4))
            #expect(Set(ids.map(\.matchKey)).count == ids.count)
        }
    }

    @Test func interactiveRatioUsesOnlyInteractiveElements() {
        // 4 个 Row 全部落 K4（容器），1 个按钮靠标题落 K2。整树 K4 比例高，可交互 K4 比例为 0。
        let rows = (0..<4).map { _ in AXNode(role: "AXRow") }
        let root = Self.win(rows + [AXNode(role: "AXButton", title: "Go")])
        let r = IdentityAnalyzer.report(root)
        #expect(r.interactive.total == 1)
        #expect(r.interactive.ratio(.k4) == 0)
        #expect(r.all.count(.k4) == 4)
    }

    @Test func emptyInteractiveSetHasNoRatioRatherThanZero() {
        let r = IdentityAnalyzer.report(Self.win([AXNode(role: "AXGroup")]))
        #expect(r.interactive.total == 0)
        #expect(r.interactive.ratio(.k4) == nil)
    }
}
